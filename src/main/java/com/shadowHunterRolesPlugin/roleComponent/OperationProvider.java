package com.shadowHunterRolesPlugin.roleComponent;

/**
 * **组件操作面**（阶段 13 · t120 · 设计定案 §2 / §10）：让**外部指令面**（管理员 / 调试面）能按
 * 「玩家 + 组件 id」操作任意组件状态 —— 组件**自行选择实现**本接口 ✓；没实现的组件**不支持**操作指令 ✗。
 *
 * <h2>契约（只有一个方法）</h2>
 * <ul>
 *   <li>{@code true} = **已识别并已按其语义处理** —— **不论语义上成功与否** ✓（例：{@code consume} 因能量不足
 *       而未扣，仍算"已识别并按语义处理"：组件内部把"不扣、不产生变更"当作该语义的结果 ✓）；</li>
 *   <li>{@code false} = **未识别**（未知动词 / 空 payload）或**拒绝执行**（语法错 / 参数不合法）。</li>
 * </ul>
 * 参数 = **整段 payload 字符串**（v2 定案：op 与 args **合并**后交给组件自解析 ✓）—— 本接口**不解析**它 ✗。
 *
 * <h2>★ 三条护栏（防先例 · 设计定案 §10.2）</h2>
 * <ol>
 *   <li><b>冻结为单方法</b> ✗：本接口**不得再加方法、不得加默认实现**；组件需要更多能力 ⇒
 *       暴露**自己的**方法 ✓（**不扩本接口** ✗）；</li>
 *   <li><b>包定位 = 组件契约</b>：本接口落在 {@code roleComponent/} ✓ —— **不进** {@code core/} 的
 *       "公共能力区" ✗（后者已被 R-1 清空）；</li>
 *   <li><b>若将来两个以上组件需要同一操作面</b> ⇒ 走"**折进组件**"的既有做法 ✓，
 *       **不再加顶层接口** ✗。</li>
 * </ol>
 *
 * <h2>★ R-8 判据（本接口为什么允许存在 · 设计定案 §10.1）</h2>
 * <ul>
 *   <li>✅ <b>允许</b>：能力接口表达的东西**不可能成为组件**时 ⇒ 可做接口 ✓ ——
 *       "可被外部指令操作"是一个**跨切面开关**：**无状态**、**无生命周期**、**不按实例持有** ✓；</li>
 *   <li>✗ <b>禁止</b>：表达的东西**符合组件定义**时（拥有状态 / 生命周期 / 按实例持有）⇒ 一律做成组件 ✓
 *       （冷却状态 · 热键栏提供 · 耗能声明都已被折进组件 ⇒ 那些接口**完全多余** ✗）。</li>
 * </ul>
 *
 * <h2>payload 约定（设计定案 §10.4）</h2>
 * <b>首 token 必为操作动词</b> ✓（如 {@code add 5} / {@code consume 3} / {@code current} / {@code set 120}）——
 * 派发器可**可选地**取首 token 用于权限校验与 Tab 补全 ✓（组件仍可忽略 ✓）；
 * 其余部分由**组件自解析** ✓ ⇒ **grammar 必须写进实现它的组件的 javadoc** ✓（本接口**不规定** grammar ✗）。
 *
 * <h2>本片范围（如实申报）</h2>
 * 本接口 + **能量组件试点** = 阶段 13 的第一片 ✓；**指令面 / 派发器 / {@code RoleAPI} 收口**不在本片 ✗
 * （分别归后续卡 ✓）。
 */
public interface OperationProvider {

    /**
     * 处理一条操作指令（**整段 payload 原样交给组件** ✓）。
     *
     * @param payload 整段剩余文本（**可含空格**）；{@code null} / 空串 / 纯空白 的语义**由组件自行定义** ✓
     *                （但必须写进该组件的 javadoc ✓）
     * @return {@code true} = 已识别并已按其语义处理（**不论语义上成功与否** ✓）；
     *         {@code false} = 未识别（未知动词 / 空 payload）或拒绝执行（语法错 / 参数不合法）
     */
    boolean onOperationCommand(String payload);
}
